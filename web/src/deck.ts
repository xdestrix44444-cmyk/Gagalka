export interface Arcana {
  /** 0–21 старшие арканы, 22–77 младшие: жезлы, кубки, мечи, пентакли (туз … король). */
  id: number
  /** Номинал на карте: римское число. */
  numeral: string
  name: string
  /** «Имя файла» карты в терминальном логе, например 16_БАШНЯ.EXE. */
  file: string
  /** Толкование карты. Временный текст до подключения ИИ. */
  text: string
  /** Масть младшего аркана; у старших не задана. */
  suit?: Suit
}

export type IntegrityState = 'whole' | 'partial' | 'damaged'

export function integrityState(integrity: number): IntegrityState {
  if (integrity >= 90) return 'whole'
  if (integrity >= 60) return 'partial'
  return 'damaged'
}

