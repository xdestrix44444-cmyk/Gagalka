export const DECK: readonly Arcana[] = [...MAJOR, ...MINOR]

/** Карта в том виде, в каком выпала с данной целостностью. */
export interface CardReading {
  state: IntegrityState
  /** Повреждённая карта лежит вверх ногами и читается тенью. */
  reversed: boolean
  text: string
  /** Строка «помеха» для частично целой карты. */
  noise?: string
}

export function readingOf(card: Arcana, integrity: number): CardReading {
  const state = integrityState(integrity)
  const layers = LAYERS[card.id]
  if (state === 'damaged') return { state, reversed: true, text: layers.shadow }
  return { state, reversed: false, text: card.text, noise: state === 'partial' ? layers.noise : undefined }
}

