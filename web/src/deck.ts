export const ACTIVE_IDS: readonly number[] = [...Array.from({ length: 22 }, (_, i) => i), 23, 42]
export const ACTIVE_DECK: readonly Arcana[] = DECK.filter((c) => ACTIVE_IDS.includes(c.id))
