// Расклады «Нити»: быстрые (да/нет, одна карта), на три карты, тематические и кельтский крест.
// Общие для приложения, сервера толкований и дневника.

export type SpreadKind = 'yesno' | 'one' | 'three' | 'time' | 'love' | 'work' | 'choice' | 'celtic'

/** Как карты лежат на столе: класс .spread-<layout> в styles.css. */
export type SpreadLayout = 'one' | 'row' | 'love' | 'choice' | 'celtic'

export interface Position {
  name: string
  /** Что означает место в раскладе: подсказка человеку и ИИ-толкователю. */
  hint: string
}

export interface Spread {
  kind: SpreadKind
  name: string
  /** Короткая строка на выборе расклада: для какого вопроса он нужен. */
  line: string
  layout: SpreadLayout
  /** Объём толкования для ИИ: так короткий вопрос не тратит токены на длинный ответ. */
  words: string
  positions: Position[]
}

