/** Поиск по началу названия (и прежних названий), без учёта регистра, «ё» и дефисов. */
export function findCities(query: string, limit = 8): City[] {
  const q = fold(query)
  if (!q) return []
  const names = (c: City) => [c.name, ...(FORMER[c.name] ?? [])].map(fold)
  const starts = CITIES.filter((c) => names(c).some((n) => n.startsWith(q)))
  const inside = CITIES.filter((c) => !starts.includes(c) && names(c).some((n) => n.includes(q)))
  return [...starts, ...inside].slice(0, limit)
}
