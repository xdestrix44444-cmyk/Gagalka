export const CITIES: readonly City[] = RAW.map(([name, region, lat, lon, tz]) => ({ name, region, lat, lon, tz }))

const fold = (s: string) => s.toLowerCase().replace(/ё/g, 'е').replace(/[^a-zа-я0-9]/g, '')

/** Поиск по началу названия, без учёта регистра, «ё» и дефисов. */
export function findCities(query: string, limit = 8): City[] {
  const q = fold(query)
  if (!q) return []
  const starts = CITIES.filter((c) => fold(c.name).startsWith(q))
  const inside = CITIES.filter((c) => !starts.includes(c) && fold(c.name).includes(q))
  return [...starts, ...inside].slice(0, limit)
}
