/** Сфера дома: где это звучит сильнее всего. */
export const HOUSE_SPHERE = [
  'вы сами и то, каким вас видят',
  'деньги и то, на что вы опираетесь',
  'общение, учёба и ближний круг',
  'дом, семья и корни',
  'творчество, любовь и радость',
  'работа, быт и здоровье',
  'партнёрство и близкий человек',
  'близость, кризисы и перемены',
  'путешествия и поиск смысла',
  'призвание и репутация',
  'друзья и планы на будущее',
  'внутренний мир и тишина',
] as const

const GENERATIONAL: PlanetKey[] = ['uranus', 'neptune', 'pluto']

export function planetMeaning(p: PlanetPos): string {
  const parts: string[] = []
  if (GENERATIONAL.includes(p.key))
    parts.push(`Вы ${ACT[p.key]} так же, как ваше поколение: этот знак общий для всех, кто родился в те годы.`)
  else parts.push(`Вы ${ACT[p.key]} — ${HOW[p.sign]}.`)
  if (p.house) parts.push(`Сильнее всего это звучит в сфере «${HOUSE_SPHERE[p.house - 1]}».`)
  if (p.retro) parts.push('Планета ретроградна: энергия обращена внутрь, вы долго обдумываете, прежде чем проявить.')
  return parts.join(' ')
}

/** Северный узел: направление роста; южный узел напротив — привычное. */
export function nodeMeaning(p: PointPos): string {
  const where = p.house ? ` Сфера роста — «${HOUSE_SPHERE[p.house - 1]}».` : ''
  return `Направление, в котором вам стоит расти: ${HOW[p.sign]}.${where} Южный узел напротив — то, что даётся привычно и легко, но держит на месте.`
}

/** Лилит: вытесненная, теневая сторона. */
export function lilithMeaning(p: PointPos): string {
  const where = p.house ? ` Чаще всего тень проявляется в сфере «${HOUSE_SPHERE[p.house - 1]}».` : ''
  return `Лилит ${inSign(p.sign)} — то, что вы в себе прячете или чего боитесь: соблазн жить ${HOW[p.sign].split(',')[0]}, но без меры.${where} Признать эту сторону — значит перестать с ней воевать.`
}

export function houseMeaning(n: number, inside: PlanetPos[]): string {
  const sphere = HOUSE_SPHERE[n - 1]
  if (!inside.length) return `Сфера «${sphere}». Планет здесь нет: эта часть жизни идёт ровно и не требует постоянного внимания.`
  if (inside.length >= 3) return `Сфера «${sphere}». Здесь собралось много планет — эта часть жизни забирает у вас особенно много сил и внимания.`
  return `Сфера «${sphere}». Планеты здесь показывают, чем эта часть жизни для вас окрашена.`
}
